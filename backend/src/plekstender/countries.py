def _key(name: str) -> str:
    folded = unicodedata.normalize("NFKD", name.strip().casefold())
    text = "".join(c for c in folded if not unicodedata.combining(c))
    text = text.replace(APOSTROPHE, "'").replace("&", "and")
    return " ".join(text.split())


_BY_NAME = {_key(n): code for code, n in NAMES.items()} | {_key(k): v for k, v in ALIASES.items()}


def country_code(name: str | None) -> str | None:
    """ "United Kingdom", "USA", "Côte d'Ivoire" -> "GB", "US", "CI"; None if unknown. A
    two-letter code is taken as one."""
    if not name:
        return None
    key = _key(name)
    if len(key) == 2 and key.upper() in NAMES:
        return key.upper()
    return _BY_NAME.get(key) or _BY_NAME.get(key.removeprefix("the "))
